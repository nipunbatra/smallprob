"""Small, explicit expression graphs and probability distributions.

Graph construction is deterministic: random numbers are only generated by a
distribution's ``sample`` method, never while executing a model definition.
"""

from __future__ import annotations

from dataclasses import dataclass
import math
import numbers
from typing import Any, Mapping

import numpy as np


class ModelError(ValueError):
    """An invalid model, parameter, or observation."""


class UnsupportedModelError(ModelError):
    """A valid modelling idea outside this prototype's supported subset."""


class InferenceError(ModelError):
    """Inference cannot be completed for the supplied model or evidence."""


def _contained_dependencies(value: Any) -> set[str]:
    if isinstance(value, Expr):
        return value.dependencies()
    if isinstance(value, np.ndarray):
        if value.dtype != object:
            return set()
        value = value.flat
    if isinstance(value, dict):
        value = value.values()
    if isinstance(value, (list, tuple)) or isinstance(value, (type({}.values()), np.flatiter)):
        result: set[str] = set()
        for item in value:
            result.update(_contained_dependencies(item))
        return result
    return set()


def _resolve_container(value: Any, values: Mapping[str, Any]) -> Any:
    if isinstance(value, Expr):
        return value.eval(values)
    if isinstance(value, list):
        return [_resolve_container(item, values) for item in value]
    if isinstance(value, tuple):
        return tuple(_resolve_container(item, values) for item in value)
    if isinstance(value, dict):
        return {key: _resolve_container(item, values) for key, item in value.items()}
    if isinstance(value, np.ndarray) and value.dtype == object:
        return np.asarray([_resolve_container(item, values) for item in value.flat]).reshape(value.shape)
    return value


@dataclass(frozen=True, eq=False)
class Expr:
    """A symbolic scalar or indexed array expression in a model graph."""

    op: str
    args: tuple
    __array_priority__ = 1000

    def eval(self, values: Mapping[str, Any]) -> Any:
        if self.op == "const":
            return _resolve_container(self.args[0], values)
        if self.op == "ref":
            try:
                return values[self.args[0]]
            except KeyError as exc:
                raise ModelError(f"No value supplied for random variable {self.args[0]!r}.") from exc
        if self.op == "neg":
            return -self.args[0].eval(values)
        left, right = (arg.eval(values) for arg in self.args)
        if self.op == "add":
            return left + right
        if self.op == "sub":
            return left - right
        if self.op == "mul":
            return left * right
        if self.op == "div":
            return left / right
        if self.op == "pow":
            return left ** right
        if self.op == "index":
            try:
                return left[right]
            except (TypeError, IndexError, KeyError) as exc:
                raise ModelError(f"Invalid symbolic index {right!r}: {exc}") from exc
        raise UnsupportedModelError(f"Unknown expression operation {self.op!r}.")

    def dependencies(self) -> set[str]:
        if self.op == "ref":
            return {self.args[0]}
        if self.op == "const":
            return _contained_dependencies(self.args[0])
        result: set[str] = set()
        for argument in self.args:
            result.update(argument.dependencies())
        return result

    def __add__(self, other):
        return Expr("add", (self, as_expr(other)))

    def __radd__(self, other):
        return Expr("add", (as_expr(other), self))

    def __sub__(self, other):
        return Expr("sub", (self, as_expr(other)))

    def __rsub__(self, other):
        return Expr("sub", (as_expr(other), self))

    def __mul__(self, other):
        return Expr("mul", (self, as_expr(other)))

    def __rmul__(self, other):
        return Expr("mul", (as_expr(other), self))

    def __truediv__(self, other):
        return Expr("div", (self, as_expr(other)))

    def __rtruediv__(self, other):
        return Expr("div", (as_expr(other), self))

    def __pow__(self, other):
        return Expr("pow", (self, as_expr(other)))

    def __rpow__(self, other):
        return Expr("pow", (as_expr(other), self))

    def __neg__(self):
        return Expr("neg", (self,))

    def __pos__(self):
        return self

    def __getitem__(self, index):
        return Expr("index", (self, as_expr(index)))

    def _unresolved(self, operation):
        raise UnsupportedModelError(
            f"Cannot {operation} a random variable while building a model. "
            "Use fixed inputs for Python branches, loop bounds and shapes; "
            "use symbolic arithmetic or indexing for random dependencies."
        )

    def __bool__(self):
        self._unresolved("use as a condition")

    def __float__(self):
        self._unresolved("convert to float")

    def __int__(self):
        self._unresolved("convert to int")

    def __index__(self):
        self._unresolved("use as a Python integer")

    def __len__(self):
        self._unresolved("take the length of")

    def __iter__(self):
        self._unresolved("iterate over")

    def __array__(self, dtype=None, copy=None):
        self._unresolved("convert to a NumPy array")

    def __eq__(self, other):
        self._unresolved("compare")

    def __ne__(self, other):
        self._unresolved("compare")

    def __lt__(self, other):
        self._unresolved("compare")

    def __le__(self, other):
        self._unresolved("compare")

    def __gt__(self, other):
        self._unresolved("compare")

    def __ge__(self, other):
        self._unresolved("compare")

    def __array_ufunc__(self, ufunc, method, *inputs, **kwargs):
        operations = {
            np.add: "add", np.subtract: "sub", np.multiply: "mul",
            np.divide: "div", np.true_divide: "div", np.power: "pow",
            np.negative: "neg",
        }
        if method == "__call__" and not kwargs and ufunc in operations:
            return Expr(operations[ufunc], tuple(as_expr(item) for item in inputs))
        raise UnsupportedModelError(
            f"NumPy operation {ufunc.__name__!r} is not supported on symbolic values. "
            "This prototype supports arithmetic and indexing."
        )


def as_expr(value: Any) -> Expr:
    if isinstance(value, Expr):
        return value
    return Expr("const", (_snapshot(value),))


def _snapshot(value: Any) -> Any:
    """Keep a bound model stable when callers later mutate its input arrays."""
    if isinstance(value, Expr):
        return value
    # Fixed tensor inputs are immutable model data, not differentiable leaves.
    # Explicitly detach and transfer them before NumPy sees the snapshot.
    from .arrays import is_torch_array, to_numpy
    if is_torch_array(value):
        return to_numpy(value)
    if isinstance(value, list):
        return [_snapshot(item) for item in value]
    if isinstance(value, tuple):
        return tuple(_snapshot(item) for item in value)
    if isinstance(value, dict):
        return {key: _snapshot(item) for key, item in value.items()}
    if isinstance(value, np.ndarray):
        if value.dtype == object:
            result = np.empty(value.shape, dtype=object)
            for index in np.ndindex(value.shape):
                result[index] = _snapshot(value[index])
            return result
        return value.copy()
    return value


def lookup(base: Any, index: Any) -> Any:
    """Preserve ordinary indexing, deferring lookups with a random index."""
    if isinstance(index, slice) and any(isinstance(v, Expr) for v in (index.start, index.stop, index.step)):
        raise UnsupportedModelError("Random slice bounds are not supported; use a scalar random index.")
    if isinstance(base, Expr) or isinstance(index, Expr) or _contained_dependencies(index):
        return Expr("index", (as_expr(base), as_expr(index)))
    return base[index]


def _scalar(value: Any, label: str) -> float:
    if isinstance(value, np.ndarray) and value.ndim == 0:
        value = value.item()
    if isinstance(value, (bool, np.bool_)) or not isinstance(value, numbers.Real):
        raise ModelError(f"{label} must be a finite real scalar, got {value!r}.")
    try:
        number = float(value)
    except (ValueError, OverflowError) as exc:
        raise ModelError(f"{label} must fit in a finite floating point scalar.") from exc
    if not np.isfinite(number):
        raise ModelError(f"{label} must be finite, got {value!r}.")
    return number


def _broadcast_components(left, right):
    """Align scalar expressions or one-dimensional tuples without sampling."""
    left_vector, right_vector = isinstance(left, tuple), isinstance(right, tuple)
    if not left_vector and not right_vector:
        return None
    if left_vector and right_vector:
        a, b = len(left), len(right)
        if a != b and a != 1 and b != 1:
            raise ModelError(f"Distribution parameters have incompatible vector lengths {a} and {b}.")
        size = b if a == 1 else a
    else:
        size = len(left) if left_vector else len(right)
    return tuple((left[0 if len(left) == 1 else i] if left_vector else left,
                  right[0 if len(right) == 1 else i] if right_vector else right)
                 for i in range(size))


def _container_shape(value):
    """Inspect fixed container dimensions without coercing any symbolic values."""
    if isinstance(value, Expr):
        components = _scalar_components(value)
        return (len(components),) if isinstance(components, tuple) else ()
    if isinstance(value, np.ndarray):
        return value.shape
    if isinstance(value, (tuple, list)):
        children = [_container_shape(item) for item in value]
        if children and any(shape != children[0] for shape in children):
            raise ModelError("Distribution parameter tables must have regular, fixed dimensions.")
        return (len(value),) + (children[0] if children else ())
    return ()


def _symbolic_index_components(expression, base, index):
    """Infer indexing dimensions algebraically; a random scalar removes an axis."""
    if base.op == "const":
        shape = _container_shape(base.args[0])
    else:
        components = _scalar_components(base)
        shape = (len(components),) if isinstance(components, tuple) else ()
        # Preserve elementwise arithmetic even when a categorical state chooses
        # the element only at sampling time.
        base = as_expr(components)
        expression = Expr("index", (base, index))
    raw_index = index.args[0] if index.op == "const" else index
    indices = raw_index if isinstance(raw_index, tuple) else (raw_index,)
    remaining = list(shape)
    result = []
    for item in indices:
        if not remaining:
            raise ModelError("Too many indices for a distribution parameter expression.")
        length = remaining.pop(0)
        if isinstance(item, Expr):
            if isinstance(_scalar_components(item), tuple):
                raise UnsupportedModelError("Random vector indices are unsupported; use one scalar categorical state.")
        elif isinstance(item, slice):
            if _contained_dependencies((item.start, item.stop, item.step)):
                raise UnsupportedModelError("Random slice bounds are unsupported.")
            result.append(len(range(length)[item]))
        elif isinstance(item, (bool, np.bool_)) or not isinstance(item, numbers.Integral):
            raise UnsupportedModelError("Symbolic parameter indexing supports only scalar integers and fixed slices.")
    result.extend(remaining)
    if len(result) > 1:
        raise ModelError("Distribution parameters must be scalar or one-dimensional after indexing.")
    if result:
        return tuple(Expr("index", (expression, as_expr(i))) for i in range(result[0]))
    return expression


def _scalar_components(expression: Expr):
    """Lower a scalar/vector expression to scalar Exprs using only fixed shapes.

    A tuple denotes a vector even when it is empty or has one item. Arithmetic
    is distributed to its elements, so neither Python list repetition nor
    list concatenation reaches numerical backends. An unresolved scalar index
    stays symbolic, preserving categorical-state emission lookups.
    """
    if expression.op == "const":
        value = expression.args[0]
        if isinstance(value, np.ndarray):
            if value.ndim == 0:
                return _scalar_components(as_expr(value.item()))
            if value.ndim != 1:
                raise ModelError("Distribution parameters must be scalar or one-dimensional; multidimensional arrays are unsupported.")
        if isinstance(value, (list, tuple, np.ndarray)):
            result = tuple(_scalar_components(as_expr(item)) for item in value)
            if any(isinstance(item, tuple) for item in result):
                raise ModelError("Distribution parameters must be scalar or one-dimensional; nested vectors are unsupported.")
            return result
        return expression
    if expression.op == "ref":
        return expression
    if expression.op == "index":
        base, index = expression.args
        if not index.dependencies():
            fixed_index = index.eval({})
            if base.op == "const":
                # Indexing a fixed table may remove dimensions before Normal
                # sees it. Keep the usual Python/NumPy indexing conventions.
                try:
                    return _scalar_components(as_expr(base.args[0][fixed_index]))
                except (TypeError, IndexError, KeyError) as exc:
                    raise ModelError(f"Invalid fixed distribution parameter index: {exc}") from exc
            components = _scalar_components(base)
            if not isinstance(components, tuple):
                raise ModelError("Cannot index a scalar distribution parameter expression.")
            try:
                selected = components[fixed_index]
            except (TypeError, IndexError) as exc:
                raise ModelError(f"Invalid fixed distribution parameter index: {exc}") from exc
            return selected
        return _symbolic_index_components(expression, base, index)
    if expression.op == "neg":
        value = _scalar_components(expression.args[0])
        return tuple(-item for item in value) if isinstance(value, tuple) else -value
    if expression.op in {"add", "sub", "mul", "div", "pow"}:
        left, right = (_scalar_components(argument) for argument in expression.args)
        aligned = _broadcast_components(left, right)
        if aligned is None:
            return Expr(expression.op, (left, right))
        return tuple(Expr(expression.op, pair) for pair in aligned)
    raise UnsupportedModelError(f"Cannot determine the shape of distribution parameter operation {expression.op!r}.")


def _normal_components(distribution):
    """Return normalized parameters and optional aligned vector parameters."""
    mean = _scalar_components(distribution.mean)
    sd = _scalar_components(distribution.sd)
    return (mean, sd), _broadcast_components(mean, sd)


def _student_t_components(distribution):
    """Align df/location/scale, retaining empty and singleton series shapes."""
    parameters = tuple(_scalar_components(getattr(distribution, field))
                       for field in ("df", "loc", "scale"))
    lengths = [len(value) for value in parameters if isinstance(value, tuple)]
    if not lengths:
        return parameters, None
    nonsingleton = set(length for length in lengths if length != 1)
    if len(nonsingleton) > 1:
        raise ModelError(f"StudentT parameters have incompatible vector lengths {lengths}.")
    size = next(iter(nonsingleton), 1)
    aligned = tuple(tuple(value[0 if len(value) == 1 else index]
                          if isinstance(value, tuple) else value
                          for value in parameters) for index in range(size))
    return parameters, aligned


class Normal:
    """Normal parameters, scalar or 1D when declared inside a model.

    A vector declaration becomes conditionally independent scalar Normal sites.
    ``sd`` is a standard deviation; scalars and singleton vectors broadcast.
    """

    def __init__(self, mean=0, sd=1):
        self.mean = as_expr(mean)
        self.sd = as_expr(sd)
        if not self.mean.dependencies():
            means = _scalar_components(self.mean)
            for value in means if isinstance(means, tuple) else (means,):
                _scalar(value.eval({}), "Normal mean")
        if not self.sd.dependencies():
            scales = _scalar_components(self.sd)
            for value in scales if isinstance(scales, tuple) else (scales,):
                if _scalar(value.eval({}), "Normal sd") <= 0:
                    raise ModelError("Normal sd must be strictly positive.")

    def dependencies(self) -> set[str]:
        return self.mean.dependencies() | self.sd.dependencies()

    def _parameters(self, values):
        mu = _scalar(self.mean.eval(values), "Normal mean")
        sigma = _scalar(self.sd.eval(values), "Normal sd")
        if sigma <= 0:
            raise ModelError("Normal sd must be strictly positive.")
        return mu, sigma

    def sample(self, values, rng) -> float:
        mu, sigma = self._parameters(values)
        return float(rng.normal(mu, sigma))

    def log_prob(self, value, values) -> float:
        mu, sigma = self._parameters(values)
        value = _scalar(value, "Normal value")
        with np.errstate(over="ignore", divide="ignore", invalid="ignore"):
            residual = np.float64(value - mu) / sigma
            return float(-0.5 * np.log(2 * np.pi) - np.log(sigma) - 0.5 * np.square(residual))


class HalfNormal:
    """A nonnegative scalar with the distribution of ``abs(Normal(0, sd))``.

    ``sd`` is the scale of the underlying Normal, not the standard deviation
    of the resulting HalfNormal. The density includes zero in its support.
    """

    def __init__(self, sd=1):
        self.sd = as_expr(sd)
        if not self.sd.dependencies():
            self._scale({})

    def dependencies(self) -> set[str]:
        return self.sd.dependencies()

    def _scale(self, values):
        sigma = _scalar(self.sd.eval(values), "HalfNormal sd")
        if sigma <= 0:
            raise ModelError("HalfNormal sd must be strictly positive.")
        return sigma

    def sample(self, values, rng) -> float:
        return abs(float(rng.normal(0, self._scale(values))))

    def log_prob(self, value, values) -> float:
        sigma = self._scale(values)
        value = _scalar(value, "HalfNormal value")
        if value < 0:
            return float("-inf")
        with np.errstate(over="ignore", divide="ignore", invalid="ignore"):
            residual = np.float64(value) / sigma
            return float(0.5 * np.log(2 / np.pi) - np.log(sigma) - 0.5 * np.square(residual))


class StudentT:
    """Student's t distribution with degrees of freedom, location and scale.

    ``loc`` is a location parameter; the mean exists only for ``df > 1``.
    ``scale`` is not a standard deviation: variance is
    ``scale**2 * df / (df - 2)`` only for ``df > 2``. Parameters can be
    scalar or one-dimensional inside a model, as with :class:`Normal`.
    """

    def __init__(self, df, loc=0, scale=1):
        self.df = as_expr(df)
        self.loc = as_expr(loc)
        self.scale = as_expr(scale)
        for field in ("df", "loc", "scale"):
            expression = getattr(self, field)
            if not expression.dependencies():
                components = _scalar_components(expression)
                for component in components if isinstance(components, tuple) else (components,):
                    value = _scalar(component.eval({}), f"StudentT {field}")
                    if field != "loc" and value <= 0:
                        raise ModelError(f"StudentT {field} must be strictly positive.")

    def dependencies(self) -> set[str]:
        return self.df.dependencies() | self.loc.dependencies() | self.scale.dependencies()

    def _parameters(self, values):
        df, loc, scale = (_scalar(getattr(self, field).eval(values), f"StudentT {field}")
                          for field in ("df", "loc", "scale"))
        if df <= 0:
            raise ModelError("StudentT df must be strictly positive.")
        if scale <= 0:
            raise ModelError("StudentT scale must be strictly positive.")
        return df, loc, scale

    def sample(self, values, rng) -> float:
        df, loc, scale = self._parameters(values)
        return float(loc + scale * rng.standard_t(df))

    def log_prob(self, value, values) -> float:
        df, loc, scale = self._parameters(values)
        value = _scalar(value, "StudentT value")
        # The ratio of gamma functions loses precision for very large df.
        # Its first asymptotic correction also gives the Normal limit.
        if df < 1e-8:
            # log(Gamma(df/2)) ~ -log(df/2) - EulerGamma*df/2.
            # Taking log(df) before halving also handles subnormal positive df.
            normalizer = (math.lgamma((df + 1) / 2) + math.log(df) - math.log(2)
                          + 0.5772156649015329 * (0.5 * df)
                          - 0.5 * (math.log(df) + math.log(math.pi)))
        elif df >= 1e8:
            normalizer = -0.5 * math.log(2 * math.pi) - 0.25 / df
        else:
            normalizer = (math.lgamma((df + 1) / 2) - math.lgamma(df / 2)
                          - 0.5 * (math.log(df) + math.log(math.pi)))
        delta = value - loc
        if delta == 0:
            tail = 0.0
        else:
            log_delta = (float(np.logaddexp(math.log(abs(value)), math.log(abs(loc))))
                         if math.isinf(delta) else math.log(abs(delta)))
            log_ratio = 2 * (log_delta - math.log(scale)) - math.log(df)
            tail = float(np.logaddexp(0.0, log_ratio))
        return float(normalizer - math.log(scale) - (0.5 * df + 0.5) * tail)


class Categorical:
    """A scalar zero-based category with explicitly normalised probabilities."""

    def __init__(self, probs):
        self.probs = as_expr(probs)
        if not self.probs.dependencies():
            self._probabilities({})

    def dependencies(self) -> set[str]:
        return self.probs.dependencies()

    def _probabilities(self, values) -> np.ndarray:
        raw = self.probs.eval(values)
        try:
            probabilities = np.asarray(raw)
            if probabilities.dtype.kind not in "iuf":
                raise ValueError("probabilities must be real numbers")
            tolerance = max(1e-8, 4 * np.finfo(probabilities.dtype).eps) if probabilities.dtype.kind == "f" else 1e-8
            probabilities = probabilities.astype(float)
        except (ValueError, TypeError) as exc:
            raise ModelError(f"Categorical probabilities must be a numeric vector: {exc}") from exc
        if probabilities.ndim != 1 or len(probabilities) == 0:
            raise ModelError("Categorical probabilities must be a nonempty one-dimensional vector.")
        if not np.all(np.isfinite(probabilities)) or np.any(probabilities < 0):
            raise ModelError("Categorical probabilities must be finite and nonnegative.")
        total = probabilities.sum()
        if not np.isclose(total, 1.0, atol=tolerance, rtol=0):
            raise ModelError(
                f"Categorical probabilities must sum to 1, got {probabilities.sum():.12g}; "
                "normalise them explicitly."
            )
        # Remove accepted input-rounding error consistently for sampling,
        # density evaluation and exact inference; arbitrary weights still fail.
        return probabilities / total

    def sample(self, values, rng) -> int:
        probabilities = self._probabilities(values)
        return int(rng.choice(len(probabilities), p=probabilities))

    def log_prob(self, value, values) -> float:
        probabilities = self._probabilities(values)
        number = _scalar(value, "Categorical value")
        if not number.is_integer():
            raise ModelError(f"Categorical values must be integer indices, got {value!r}.")
        category = int(number)
        if category < 0 or category >= len(probabilities):
            raise ModelError(f"Categorical index {category} is outside [0, {len(probabilities) - 1}].")
        probability = probabilities[category]
        return float(np.log(probability)) if probability > 0 else float("-inf")


@dataclass
class Node:
    name: str
    distribution: Normal | HalfNormal | StudentT | Categorical


@dataclass
class Graph:
    nodes: list[Node]
    groups: dict[str, list[str]]
    series: set[str]

    def __post_init__(self):
        seen: set[str] = set()
        for node in self.nodes:
            if node.name in seen:
                raise ModelError(f"Duplicate random variable name {node.name!r}.")
            if not isinstance(node.distribution, (Normal, HalfNormal, StudentT, Categorical)):
                raise UnsupportedModelError("Only Normal, HalfNormal, StudentT and Categorical distributions are supported.")
            missing = node.distribution.dependencies() - seen
            if missing:
                raise ModelError(f"Variable {node.name!r} refers to unavailable earlier variables: {sorted(missing)}.")
            seen.add(node.name)
        members = [name for names in self.groups.values() for name in names]
        if len(members) != len(set(members)) or set(members) != seen:
            raise ModelError("Graph groups must contain every random variable exactly once.")
        if not self.series.issubset(self.groups):
            raise ModelError("Every series must have a corresponding graph group.")
        for group, names in self.groups.items():
            if group not in self.series and names != [group]:
                raise ModelError(f"Scalar group {group!r} must contain exactly its own variable.")

    def expand_values(self, mapping, allow_missing=False) -> dict[str, Any]:
        if not isinstance(mapping, Mapping):
            raise ModelError("Values must be a mapping from variable names to scalars or series.")
        sites = {node.name for node in self.nodes}
        expanded: dict[str, Any] = {}
        assigned: set[str] = set()

        def add(name, value):
            if name in assigned:
                raise ModelError(f"Value for {name!r} was supplied more than once (group and indexed name overlap).")
            assigned.add(name)
            if isinstance(value, np.ndarray) and value.ndim == 0:
                value = value.item()
            if value is None:
                if allow_missing:
                    return
                raise ModelError(f"None is not a fixed value for {name!r}.")
            if np.ndim(value) != 0:
                raise ModelError(f"Value for {name!r} must be a scalar, got shape {np.shape(value)}.")
            expanded[name] = value

        for key, value in mapping.items():
            if key in self.groups and key in self.series:
                try:
                    array = np.asarray(value, dtype=object)
                except (TypeError, ValueError) as exc:
                    raise ModelError(f"Values for series {key!r} must be one-dimensional.") from exc
                members = self.groups[key]
                if array.ndim != 1 or len(array) != len(members):
                    raise ModelError(f"Series {key!r} needs shape ({len(members)},), got {array.shape}.")
                for name, item in zip(members, array):
                    add(name, item)
            elif key in sites:
                add(key, value)
            else:
                raise ModelError(f"Unknown variable {key!r}. Available groups: {', '.join(self.groups) or '(none)' }.")
        return expanded

    def pack(self, flat: Mapping[str, Any]) -> dict[str, Any]:
        result = {}
        for group, names in self.groups.items():
            missing = [name for name in names if name not in flat]
            if missing:
                raise ModelError(f"Cannot pack {group!r}; missing values for {missing}.")
            if group in self.series:
                result[group] = np.stack([flat[name] for name in names], axis=-1) if names else np.empty(0)
            else:
                result[group] = flat[names[0]]
        return result

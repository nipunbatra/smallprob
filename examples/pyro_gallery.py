"""Three small models translated from official Pyro examples.

Run ``python -m examples.pyro_gallery`` for generation, inference and reference
checks. Source links and every adaptation are recorded in docs/pyro-examples.md.
The model bodies deliberately have no plates, guides or observation plumbing.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import time

import numpy as np

from smallprob import HalfNormal, Normal, model


SOURCES = {
    "weighing_scale": "https://pyro.ai/examples/intro_part_ii.html",
    "interaction_regression": "https://pyro.ai/examples/intro_long.html",
    "eight_schools": "https://github.com/pyro-ppl/pyro/blob/1.9.1/examples/eight_schools/mcmc.py",
    "eight_schools_data": "https://github.com/pyro-ppl/pyro/blob/1.9.1/examples/eight_schools/data.py",
}

# Existing prototype accuracy limits, declared before running these examples.
VI_THRESHOLDS = {"max_mean_error_in_reference_sd": 0.35,
                 "max_sd_relative_error": 0.20}
QUADRATURE_THRESHOLDS = {"max_absolute_moment_change": 1e-6,
                         "max_estimated_mass_outside_original_range": 1e-7}

# These eight published observations are not simulated data.
SCHOOL_EFFECTS = np.array([28., 8., -3., 7., -1., 1., 18., 12.])
SCHOOL_SE = np.array([15., 10., 16., 11., 9., 11., 10., 18.])


@model
def weighing_scale(guess=8.5):
    """Faithful model from Pyro's older, now-deprecated inference tutorial."""
    weight = Normal(guess, 1)
    measurement = Normal(weight, 0.75)


@model
def interaction_regression(group, x):
    """Pyro's two predictors plus interaction; HalfNormal replaces Uniform."""
    intercept = Normal(0, 10)
    group_effect = Normal(0, 1)
    slope = Normal(0, 1)
    interaction = Normal(0, 1)
    sigma = HalfNormal(1)
    y = Normal(intercept + group_effect * group + slope * x + interaction * group * x, sigma)


@model
def interaction_known_noise(group, x, noise=0.5):
    """Companion exact case: the same coefficient priors with fixed noise."""
    intercept = Normal(0, 10)
    group_effect = Normal(0, 1)
    slope = Normal(0, 1)
    interaction = Normal(0, 1)
    y = Normal(intercept + group_effect * group + slope * x + interaction * group * x, noise)


@model
def eight_schools(se=SCHOOL_SE):
    """Non-centered Eight Schools with an explicit HalfNormal(5) adaptation."""
    mu = Normal(0, 10)
    tau = HalfNormal(5)
    eta = Normal(np.zeros(len(se)), 1)
    y = Normal(mu + tau * eta, se)


def interaction_data(seed=103):
    """Balanced synthetic predictors, generated by the model at fixed truth."""
    x = np.tile(np.linspace(-1.5, 1.5, 20), 2)
    group = np.repeat([0., 1.], 20)
    truth = {"intercept": 1.2, "group_effect": 0.7, "slope": -0.6,
             "interaction": 0.9, "sigma": 0.5}
    generated = interaction_regression(group, x).simulate(seed=seed, fixed=truth)
    return group, x, generated["y"][0], truth


def _grid_weights(log_density):
    weights = np.exp(log_density - np.max(log_density))
    weights[[0, -1]] *= 0.5
    return weights / weights.sum()


def interaction_reference(group, x, y, *, noise=None, points=8193,
                          log_bounds=(-12., 3.)):
    """Independent conjugate calculation, integrating sigma numerically if needed."""
    design = np.column_stack([np.ones(len(x)), group, x, group * x])
    prior_precision = np.diag([0.01, 1., 1., 1.])
    if noise is not None:
        covariance = np.linalg.inv(prior_precision + design.T @ design / noise**2)
        mean = covariance @ design.T @ y / noise**2
        return {"kind": "analytic Gaussian", "mean": mean,
                "sd": np.sqrt(np.diag(covariance)), "covariance": covariance}
    if points < 3 or not np.isfinite(log_bounds).all() or not log_bounds[0] < log_bounds[1]:
        raise ValueError("Expected at least three grid points and increasing finite log bounds.")
    log_sigma = np.linspace(*log_bounds, points)
    sigma = np.exp(log_sigma)
    precision = prior_precision + (design.T @ design)[None] / sigma[:, None, None] ** 2
    covariance = np.linalg.inv(precision)
    mean = np.einsum("kij,j->ki", covariance, design.T @ y) / sigma[:, None] ** 2
    residual = y - mean @ design.T
    quadratic = np.sum(residual**2, axis=1) / sigma**2 + np.einsum("ki,ij,kj->k", mean, prior_precision, mean)
    log_marginal = -len(y) * log_sigma - 0.5 * np.linalg.slogdet(precision)[1] - 0.5 * quadratic
    weights = _grid_weights(log_marginal - sigma**2 / 2 + log_sigma)
    conditional_mean = np.column_stack([mean, sigma])
    result_mean = weights @ conditional_mean
    centered = conditional_mean - result_mean
    result_covariance = (centered * weights[:, None]).T @ centered
    result_covariance[:4, :4] += np.einsum("k,kij->ij", weights, covariance)
    return {"kind": "numerical log-sigma quadrature after integrating coefficients",
            "mean": result_mean, "sd": np.sqrt(np.diag(result_covariance)),
            "covariance": result_covariance,
            "grid": {"log_sigma_bounds": list(log_bounds), "points": points},
            "_log_scale": log_sigma, "_weights": weights}


def schools_reference(y=SCHOOL_EFFECTS, se=SCHOOL_SE, *, points=8193,
                      log_bounds=(-16., 4.)):
    """One-dimensional quadrature after integrating mu and all school effects.

    Conditional on tau, y has diagonal noise se**2 + tau**2 and a common
    Normal(0, 10) mean. The result targets our HalfNormal(5) model, not Pyro's
    original HalfCauchy prior. No Smallprob inference code is used here.
    """
    y, se = np.asarray(y), np.asarray(se)
    if points < 3 or not np.isfinite(log_bounds).all() or not log_bounds[0] < log_bounds[1]:
        raise ValueError("Expected at least three grid points and increasing finite log bounds.")
    log_tau = np.linspace(*log_bounds, points)
    tau = np.exp(log_tau)
    variance = se[None] ** 2 + tau[:, None] ** 2
    mu_variance = 1 / (0.01 + np.sum(1 / variance, axis=1))
    mu_mean = mu_variance * np.sum(y / variance, axis=1)
    residual = y - mu_mean[:, None]
    quadratic = np.sum(residual**2 / variance, axis=1) + mu_mean**2 / 100
    log_marginal = -0.5 * (np.sum(np.log(variance), axis=1) - np.log(mu_variance) + quadratic)
    weights = _grid_weights(log_marginal - 0.5 * (tau / 5)**2 + log_tau)
    means = weights @ np.column_stack([mu_mean, tau])
    variances = weights @ (np.column_stack([mu_mean, tau]) - means)**2
    variances[0] += weights @ mu_variance
    shrinkage = tau[:, None] ** 2 / variance
    conditional_effect = shrinkage * y + (1 - shrinkage) * mu_mean[:, None]
    conditional_variance = shrinkage * se**2 + (1 - shrinkage)**2 * mu_variance[:, None]
    effect_mean = weights @ conditional_effect
    effect_variance = weights @ (conditional_variance + (conditional_effect - effect_mean)**2)
    return {"kind": "numerical log-tau quadrature after integrating mu and effects",
            "mean": means, "sd": np.sqrt(variances),
            "effect_mean": effect_mean, "effect_sd": np.sqrt(effect_variance),
            "grid": {"log_tau_bounds": list(log_bounds), "points": points},
            "_log_scale": log_tau, "_weights": weights}


def quadrature_check(coarse, refined, expanded):
    """Check grid spacing and truncated range separately, including effect moments.

    Tail mass is a numerical estimate under the wider normalized grid, not a
    rigorous bound on probability beyond that wider grid.
    """
    keys = [name for name in ("mean", "sd", "effect_mean", "effect_sd") if name in coarse]
    changes = {}
    for label, other in (("grid_refinement", coarse), ("range_expansion", expanded)):
        changes[label] = {f"{name}_max_absolute_change": float(np.max(np.abs(other[name] - refined[name])))
                          for name in keys}
    lower, upper = coarse["_log_scale"][[0, -1]]
    outside = (expanded["_log_scale"] < lower) | (expanded["_log_scale"] > upper)
    tail_mass = float(expanded["_weights"][outside].sum())
    maximum_change = max(value for values in changes.values() for value in values.values())
    return {**changes,
            "grid_refinement_max_moment_change": max(changes["grid_refinement"].values()),
            "original_grid": coarse["grid"], "expanded_grid": expanded["grid"],
            "estimated_posterior_mass_outside_original_range": tail_mass,
            "tail_mass_interpretation": "Estimate under expanded numerical grid; not a rigorous bound beyond that grid.",
            "thresholds": QUADRATURE_THRESHOLDS,
            "passed": maximum_change < QUADRATURE_THRESHOLDS["max_absolute_moment_change"]
                      and tail_mass < QUADRATURE_THRESHOLDS["max_estimated_mass_outside_original_range"]}


def pyro_log_joint_checks():
    """Direct independent Pyro models check the probability law at fixed values."""
    import pyro
    import pyro.distributions as dist
    import torch

    tensor = lambda value: torch.tensor(value, dtype=torch.float64)

    def pyro_scale(guess):
        weight = pyro.sample("weight", dist.Normal(tensor(guess), tensor(1.)))
        pyro.sample("measurement", dist.Normal(weight, tensor(0.75)))

    def pyro_interaction(group, x):
        b = pyro.sample("intercept", dist.Normal(tensor(0.), tensor(10.)))
        a = pyro.sample("group_effect", dist.Normal(tensor(0.), tensor(1.)))
        m = pyro.sample("slope", dist.Normal(tensor(0.), tensor(1.)))
        c = pyro.sample("interaction", dist.Normal(tensor(0.), tensor(1.)))
        sigma = pyro.sample("sigma", dist.HalfNormal(tensor(1.)))
        pyro.sample("y", dist.Normal(b + a * group + m * x + c * group * x, sigma).to_event(1))

    def pyro_schools(se):
        mu = pyro.sample("mu", dist.Normal(tensor(0.), tensor(10.)))
        tau = pyro.sample("tau", dist.HalfNormal(tensor(5.)))
        eta = pyro.sample("eta", dist.Normal(torch.zeros_like(se), torch.ones_like(se)).to_event(1))
        pyro.sample("y", dist.Normal(mu + tau * eta, se).to_event(1))

    group, x, y, truth = interaction_data()
    cases = [
        ("weighing_scale", weighing_scale(), pyro_scale, (8.5,), {"weight": 9.1, "measurement": 9.5}),
        ("interaction_regression", interaction_regression(group, x), pyro_interaction,
         (tensor(group), tensor(x)), {**truth, "y": y}),
        ("eight_schools", eight_schools(), pyro_schools, (tensor(SCHOOL_SE),),
         {"mu": 4., "tau": 3., "eta": np.linspace(-1, 1, 8), "y": SCHOOL_EFFECTS}),
    ]
    report = []
    for name, bound, reference_model, args, values in cases:
        conditioned = pyro.poutine.condition(reference_model, data={k: tensor(v) for k, v in values.items()})
        expected = float(pyro.poutine.trace(conditioned).get_trace(*args).log_prob_sum())
        actual = float(bound.log_prob(values))
        report.append({"name": name, "smallprob_log_joint": actual, "pyro_log_joint": expected,
                       "absolute_error": abs(actual - expected), "passed": abs(actual - expected) < 1e-10})
    return report


def _compare(posterior, names, reference):
    mean = np.array([posterior.mean(name) for name in names])
    sd = np.array([posterior.sd(name) for name in names])
    result = {"names": names, "mean": mean, "sd": sd,
            "reference_mean": reference["mean"], "reference_sd": reference["sd"],
            "max_mean_error_in_reference_sd": float(np.max(np.abs(mean - reference["mean"]) / reference["sd"])),
            "max_sd_relative_error": float(np.max(np.abs(sd / reference["sd"] - 1)))}
    result["within_vi_moment_limits"] = all(result[key] <= value for key, value in VI_THRESHOLDS.items())
    return result


def run_gallery(*, steps=4000, seed=11):
    """Run all three models and report checks, separating fidelity from VI accuracy."""
    started = time.perf_counter()
    checks = pyro_log_joint_checks()
    scale = weighing_scale()
    scale_posterior = scale.infer(measurement=9.5)
    scale_check = abs(scale_posterior.mean("weight") - 9.14) < 1e-12 and abs(scale_posterior.sd("weight") - 0.6) < 1e-12
    group, x, y, _ = interaction_data()
    exact = interaction_known_noise(group, x).infer(y=y)
    exact_comparison = _compare(exact, ["intercept", "group_effect", "slope", "interaction"],
                                interaction_reference(group, x, y, noise=0.5))
    regression = interaction_regression(group, x).infer(y=y, method="vi", steps=steps, seed=seed)
    regression_reference = interaction_reference(group, x, y)
    regression_comparison = _compare(regression, ["intercept", "group_effect", "slope", "interaction", "sigma"], regression_reference)
    schools = eight_schools().infer(y=SCHOOL_EFFECTS, method="vi", steps=steps, seed=seed)
    school_reference = schools_reference()
    school_comparison = _compare(schools, ["mu", "tau"], school_reference)
    # Refinement and range checks target the numerical references, not VI.
    convergence = {}
    for name, coarse, fine, expanded in [
        ("interaction", regression_reference, interaction_reference(group, x, y, points=16385),
         interaction_reference(group, x, y, points=10924, log_bounds=(-16, 4))),
        ("schools", school_reference, schools_reference(points=16385),
         schools_reference(points=10241, log_bounds=(-20, 5))),
    ]:
        convergence[name] = quadrature_check(coarse, fine, expanded)
    generated_schools = eight_schools().simulate(draws=2, seed=seed)
    finite = all(np.all(np.isfinite(item[key])) for item in (regression_comparison, school_comparison) for key in ("mean", "sd"))
    passed = all(c["passed"] for c in checks) and scale_check and all(c["passed"] for c in convergence.values()) and finite
    passed = passed and exact_comparison["max_mean_error_in_reference_sd"] < 1e-9 and exact_comparison["max_sd_relative_error"] < 1e-9
    return {
        "sources": SOURCES, "seed": seed, "steps": steps, "seconds": time.perf_counter() - started,
        "vi_moment_limits": VI_THRESHOLDS,
        "vi_accuracy_passed": regression_comparison["within_vi_moment_limits"] and school_comparison["within_vi_moment_limits"],
        "passed": bool(passed),
        "pass_criteria": "Pyro joint-density equivalence, exact Gaussian moments, quadrature refinement and range expansion, finite VI output. VI errors are reported separately; passing is not a convergence or calibration claim.",
        "joint_density_checks": checks,
        "scale": {"mean": scale_posterior.mean("weight"), "sd": scale_posterior.sd("weight"), "passed": scale_check,
                  "generated_measurements": scale.simulate(draws=3, seed=seed)["measurement"]},
        "interaction_exact": exact_comparison, "interaction_vi": regression_comparison,
        "schools_vi": school_comparison,
        "schools_simulation_shape": list(generated_schools["y"].shape),
        "quadrature_checks": convergence,
        "limitations": ["Interaction data are synthetic and sigma has HalfNormal(1), replacing the tutorial's Uniform(0, 10).",
                        "Eight Schools keeps the published data but uses HalfNormal(5) for tau, replacing HalfCauchy(25).",
                        "Full-rank Gaussian VI can miss the hierarchical posterior's shape and under/overestimate uncertainty."]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--steps", type=int, default=4000)
    parser.add_argument("--seed", type=int, default=11)
    parser.add_argument("--output", type=Path, default=Path("outputs/pyro-gallery-validation.json"))
    args = parser.parse_args()
    report = run_gallery(steps=args.steps, seed=args.seed)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2, default=lambda value: value.tolist()) + "\n")
    print(f"Gallery checks passed: {report['passed']}; saved {args.output}")
    for case in ("interaction_vi", "schools_vi"):
        result = report[case]
        print(f"{case}: max mean error {result['max_mean_error_in_reference_sd']:.3f} reference SD; max SD error {result['max_sd_relative_error']:.1%}")
    if not report["passed"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
